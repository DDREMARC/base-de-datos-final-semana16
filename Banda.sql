CREATE TABLE resumen_dia (
    id                  NUMBER GENERATED BY DEFAULT AS IDENTITY,
    fecha               DATE DEFAULT SYSDATE,
    categoria_metrica   VARCHAR2(30) NOT NULL, -- Clasifica entre 'METODO_PAGO' o 'MODALIDAD'
    concepto            VARCHAR2(30) NOT NULL, -- Ej: 'Efectivo', 'Tarjeta', 'Mesa', etc.
    total_clientes      NUMBER(4) NOT NULL,
    total_personas      NUMBER(4),             -- Nulo para métodos de pago, usado en mesas/para llevar
    recaudado           NUMBER(8,2) NOT NULL,  -- Monto en soles (S/)
    
    CONSTRAINT pk_resumen_dia PRIMARY KEY (id),
    CONSTRAINT ck_resumen_cat CHECK (categoria_metrica IN ('METODO_PAGO', 'MODALIDAD'))
);

