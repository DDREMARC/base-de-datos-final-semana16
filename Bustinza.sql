CREATE TABLE empleados (
    id          NUMBER GENERATED BY DEFAULT AS IDENTITY,
    codigo      VARCHAR2(20 CHAR)  NOT NULL,
    nombre      VARCHAR2(100 CHAR) NOT NULL,
    dni         VARCHAR2(8)        NOT NULL,
    telefono    VARCHAR2(20)       NOT NULL,
    cargo       VARCHAR2(20 CHAR)  NOT NULL,
    sueldo      NUMBER(8,2)        NOT NULL,
    fecha_ingreso DATE DEFAULT SYSDATE NOT NULL,
    activo      CHAR(1)            DEFAULT 'S' NOT NULL,

    CONSTRAINT pk_empleados        PRIMARY KEY (id),
    CONSTRAINT uq_empleados_codigo UNIQUE (codigo),
    CONSTRAINT uq_empleados_dni    UNIQUE (dni),
    CONSTRAINT ck_empleados_cargo  CHECK (cargo IN ('Cocinero','Mozo','Cajero','Administrador')),
    CONSTRAINT ck_empleados_sueldo CHECK (sueldo > 0),
    CONSTRAINT ck_empleados_activo CHECK (activo IN ('S','N'))
);

