CREATE TABLE mesas (
    id          NUMBER GENERATED BY DEFAULT AS IDENTITY,
    numero      NUMBER(3)         NOT NULL,
    capacidad   NUMBER(2)         NOT NULL,
    zona        VARCHAR2(20 CHAR) NOT NULL,
    estado      VARCHAR2(10 CHAR) DEFAULT 'Libre' NOT NULL,

    CONSTRAINT pk_mesas        PRIMARY KEY (id),
    CONSTRAINT uq_mesas_numero UNIQUE (numero),
    CONSTRAINT ck_mesas_cap    CHECK (capacidad > 0),
    CONSTRAINT ck_mesas_zona   CHECK (zona IN ('Salón','Terraza','Privado')),
    CONSTRAINT ck_mesas_estado CHECK (estado IN ('Libre','Ocupada','Reservada'))
);

