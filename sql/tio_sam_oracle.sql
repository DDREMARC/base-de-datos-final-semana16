-- =====================================================================
-- TABLA 1: MENU_PLATOS  (dueño: Gabriel)
-- =====================================================================
CREATE TABLE menu_platos (
  id           NUMBER GENERATED BY DEFAULT AS IDENTITY,
  codigo       VARCHAR2(20 CHAR)  NOT NULL,
  nombre       VARCHAR2(100 CHAR) NOT NULL,
  descripcion  VARCHAR2(500 CHAR),
  categoria    VARCHAR2(50 CHAR)  NOT NULL,
  precio       NUMBER(8,2)        NOT NULL,
  disponible   CHAR(1)            DEFAULT 'S' NOT NULL,
  CONSTRAINT pk_menu_platos       PRIMARY KEY (id),
  CONSTRAINT uq_menu_platos_cod   UNIQUE (codigo),
  CONSTRAINT ck_platos_categoria  CHECK (categoria IN ('Platos Comunes','Platos Mixtos','Sopas','Guarniciones','Dulces')),
  CONSTRAINT ck_platos_disponible CHECK (disponible IN ('S','N')),
  CONSTRAINT ck_platos_precio     CHECK (precio > 0)
);
CREATE INDEX idx_platos_categoria ON menu_platos (categoria);

-- =====================================================================
-- TABLA 2: CLIENTES  (dueño: Banda)
-- =====================================================================
CREATE TABLE clientes (
  id         NUMBER GENERATED BY DEFAULT AS IDENTITY,
  codigo     VARCHAR2(20 CHAR)  NOT NULL,
  nombre     VARCHAR2(100 CHAR) NOT NULL,
  dni        VARCHAR2(8)        NOT NULL,
  telefono   VARCHAR2(20)       NOT NULL,
  email      VARCHAR2(100 CHAR),
  direccion  VARCHAR2(200 CHAR) NOT NULL,
  CONSTRAINT pk_clientes        PRIMARY KEY (id),
  CONSTRAINT uq_clientes_codigo UNIQUE (codigo),
  CONSTRAINT uq_clientes_dni    UNIQUE (dni),
  CONSTRAINT ck_clientes_dni    CHECK (REGEXP_LIKE(dni, '^[0-9]{8}$'))
);

-- =====================================================================
-- TABLA 3: EMPLEADOS  (dueño: Bustinza)
-- =====================================================================
CREATE TABLE empleados (
  id             NUMBER GENERATED BY DEFAULT AS IDENTITY,
  codigo         VARCHAR2(20 CHAR)  NOT NULL,
  nombre         VARCHAR2(100 CHAR) NOT NULL,
  dni            VARCHAR2(8)        NOT NULL,
  telefono       VARCHAR2(20)       NOT NULL,
  cargo          VARCHAR2(20 CHAR)  NOT NULL,
  sueldo         NUMBER(8,2)        NOT NULL,
  fecha_ingreso  DATE DEFAULT SYSDATE NOT NULL,
  activo         CHAR(1)            DEFAULT 'S' NOT NULL,
  CONSTRAINT pk_empleados        PRIMARY KEY (id),
  CONSTRAINT uq_empleados_codigo UNIQUE (codigo),
  CONSTRAINT uq_empleados_dni    UNIQUE (dni),
  CONSTRAINT ck_empleados_cargo  CHECK (cargo IN ('Cocinero','Mozo','Cajero','Administrador')),
  CONSTRAINT ck_empleados_sueldo CHECK (sueldo > 0),
  CONSTRAINT ck_empleados_activo CHECK (activo IN ('S','N'))
);

-- =====================================================================
-- TABLA 4: USUARIOS  (dueño: Banda) — login/registro del prototipo
-- Un usuario es cliente O empleado, nunca los dos ni ninguno.
-- =====================================================================
CREATE TABLE usuarios (
  id           NUMBER GENERATED BY DEFAULT AS IDENTITY,
  usuario      VARCHAR2(50 CHAR)  NOT NULL,
  clave        VARCHAR2(100 CHAR) NOT NULL,
  rol          VARCHAR2(10 CHAR)  NOT NULL,
  cliente_id   NUMBER,
  empleado_id  NUMBER,
  activo       CHAR(1) DEFAULT 'S' NOT NULL,
  CONSTRAINT pk_usuarios          PRIMARY KEY (id),
  CONSTRAINT uq_usuarios_usuario  UNIQUE (usuario),
  CONSTRAINT fk_usuarios_cliente  FOREIGN KEY (cliente_id)  REFERENCES clientes (id),
  CONSTRAINT fk_usuarios_empleado FOREIGN KEY (empleado_id) REFERENCES empleados (id),
  CONSTRAINT ck_usuarios_rol      CHECK (rol IN ('Cliente','Empleado')),
  CONSTRAINT ck_usuarios_activo   CHECK (activo IN ('S','N')),
  CONSTRAINT ck_usuarios_uno      CHECK (
       (rol = 'Cliente'  AND cliente_id IS NOT NULL AND empleado_id IS NULL)
    OR (rol = 'Empleado' AND empleado_id IS NOT NULL AND cliente_id IS NULL))
);

-- =====================================================================
-- TABLA 5: MESAS  (dueño: Bustinza)
-- =====================================================================
CREATE TABLE mesas (
  id         NUMBER GENERATED BY DEFAULT AS IDENTITY,
  numero     NUMBER(3)         NOT NULL,
  capacidad  NUMBER(2)         NOT NULL,
  zona       VARCHAR2(20 CHAR) NOT NULL,
  estado     VARCHAR2(10 CHAR) DEFAULT 'Libre' NOT NULL,
  CONSTRAINT pk_mesas        PRIMARY KEY (id),
  CONSTRAINT uq_mesas_numero UNIQUE (numero),
  CONSTRAINT ck_mesas_cap    CHECK (capacidad > 0),
  CONSTRAINT ck_mesas_zona   CHECK (zona IN ('Salón','Terraza','Privado')),
  CONSTRAINT ck_mesas_estado CHECK (estado IN ('Libre','Ocupada','Reservada'))
);

-- =====================================================================
-- TABLA 6: PEDIDOS  (dueño: Toledo) — sin columna total: se calcula del detalle
-- =====================================================================
CREATE TABLE pedidos (
  id           NUMBER GENERATED BY DEFAULT AS IDENTITY,
  cliente_id   NUMBER            NOT NULL,
  empleado_id  NUMBER            NOT NULL,
  mesa_id      NUMBER,
  fecha        DATE DEFAULT SYSDATE NOT NULL,
  modalidad    VARCHAR2(15 CHAR) NOT NULL,
  estado       VARCHAR2(15 CHAR) DEFAULT 'Pendiente' NOT NULL,
  CONSTRAINT pk_pedidos          PRIMARY KEY (id),
  CONSTRAINT fk_pedidos_cliente  FOREIGN KEY (cliente_id)  REFERENCES clientes (id),
  CONSTRAINT fk_pedidos_empleado FOREIGN KEY (empleado_id) REFERENCES empleados (id),
  CONSTRAINT fk_pedidos_mesa     FOREIGN KEY (mesa_id)     REFERENCES mesas (id),
  CONSTRAINT ck_pedidos_modal    CHECK (modalidad IN ('Mesa','Para llevar','Delivery')),
  CONSTRAINT ck_pedidos_estado   CHECK (estado IN ('Pendiente','En cocina','Entregado','Cancelado')),
  CONSTRAINT ck_pedidos_mesa     CHECK ((modalidad = 'Mesa' AND mesa_id IS NOT NULL) OR (modalidad <> 'Mesa' AND mesa_id IS NULL))
);
CREATE INDEX idx_pedidos_cliente ON pedidos (cliente_id);
CREATE INDEX idx_pedidos_fecha   ON pedidos (fecha);

-- =====================================================================
-- TABLA 7: DETALLE_PEDIDO  (dueño: Toledo)
-- =====================================================================
CREATE TABLE detalle_pedido (
  id               NUMBER GENERATED BY DEFAULT AS IDENTITY,
  pedido_id        NUMBER      NOT NULL,
  plato_id         NUMBER      NOT NULL,
  cantidad         NUMBER(3)   NOT NULL,
  precio_unitario  NUMBER(8,2) NOT NULL,
  CONSTRAINT pk_detalle_pedido PRIMARY KEY (id),
  CONSTRAINT fk_detalle_pedido FOREIGN KEY (pedido_id) REFERENCES pedidos (id),
  CONSTRAINT fk_detalle_plato  FOREIGN KEY (plato_id)  REFERENCES menu_platos (id),
  CONSTRAINT uq_detalle_linea  UNIQUE (pedido_id, plato_id),
  CONSTRAINT ck_detalle_cant   CHECK (cantidad > 0),
  CONSTRAINT ck_detalle_precio CHECK (precio_unitario > 0)
);

-- =====================================================================
-- TABLA 8: PAGOS  (dueño: Gabriel) — reemplaza a pagos_cliente
-- =====================================================================
CREATE TABLE pagos (
  id         NUMBER GENERATED BY DEFAULT AS IDENTITY,
  pedido_id  NUMBER            NOT NULL,
  metodo     VARCHAR2(15 CHAR) NOT NULL,
  monto      NUMBER(8,2)       NOT NULL,
  fecha      DATE DEFAULT SYSDATE NOT NULL,
  estado     VARCHAR2(10 CHAR) DEFAULT 'Pagado' NOT NULL,
  CONSTRAINT pk_pagos        PRIMARY KEY (id),
  CONSTRAINT fk_pagos_pedido FOREIGN KEY (pedido_id) REFERENCES pedidos (id),
  CONSTRAINT ck_pagos_metodo CHECK (metodo IN ('Efectivo','Tarjeta','Yape/Plin')),
  CONSTRAINT ck_pagos_monto  CHECK (monto > 0),
  CONSTRAINT ck_pagos_estado CHECK (estado IN ('Pagado','Pendiente','Anulado'))
);

-- =====================================================================
-- VISTA: V_RESUMEN_DIA  (dueño: Banda) — reemplaza a la tabla resumen_dia
-- =====================================================================
CREATE OR REPLACE VIEW v_resumen_dia AS
SELECT 'MODALIDAD' AS categoria_metrica, p.modalidad AS concepto,
       COUNT(DISTINCT p.id) AS total_pedidos,
       SUM(d.cantidad * d.precio_unitario) AS recaudado
FROM pedidos p JOIN detalle_pedido d ON d.pedido_id = p.id
WHERE TRUNC(p.fecha) = TRUNC(SYSDATE) AND p.estado <> 'Cancelado'
GROUP BY p.modalidad
UNION ALL
SELECT 'METODO_PAGO', g.metodo, COUNT(*), SUM(g.monto)
FROM pagos g
WHERE TRUNC(g.fecha) = TRUNC(SYSDATE) AND g.estado = 'Pagado'
GROUP BY g.metodo;

