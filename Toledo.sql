-- =========================================================
-- TABLA 8: DETALLE_PEDIDO — El Tío Sam Chifa (Oracle SQL)
-- Qué platos van dentro de cada pedido
-- =========================================================

CREATE TABLE detalle_pedido (
    id               NUMBER GENERATED BY DEFAULT AS IDENTITY,
    pedido_id        NUMBER       NOT NULL,
    plato_id         NUMBER       NOT NULL,
    cantidad         NUMBER(3)    NOT NULL,
    precio_unitario  NUMBER(8,2)  NOT NULL,             -- precio al momento de la venta

    CONSTRAINT pk_detalle_pedido  PRIMARY KEY (id),
    CONSTRAINT fk_detalle_pedido  FOREIGN KEY (pedido_id) REFERENCES pedidos (id),
    CONSTRAINT fk_detalle_plato   FOREIGN KEY (plato_id)  REFERENCES menu_platos (id),
    CONSTRAINT ck_detalle_cant    CHECK (cantidad > 0),
    CONSTRAINT ck_detalle_precio  CHECK (precio_unitario > 0)
);

