CREATE TABLE pagos_cliente (
  codigo     NUMBER GENERATED BY DEFAULT AS IDENTITY,
  cliente    VARCHAR2(100 CHAR) NOT NULL,
  compra     VARCHAR2(200 CHAR) NOT NULL,
  modalidad  VARCHAR2(15 CHAR)  NOT NULL,
  pago       VARCHAR2(15 CHAR)  NOT NULL,
  personas   NUMBER(2)          NOT NULL,
  estado     CHAR(3)            DEFAULT 'NOP' NOT NULL,
  gasto      NUMBER(8,2)        NOT NULL,

  CONSTRAINT pk_pagos_cliente   PRIMARY KEY (codigo),
  CONSTRAINT ck_pagos_modalidad CHECK (modalidad IN ('Mesa','Para llevar','Delivery')),
  CONSTRAINT ck_pagos_pago      CHECK (pago IN ('Efectivo','Tarjeta','Yape/Plin')),
  CONSTRAINT ck_pagos_estado    CHECK (estado IN ('SIP','NOP'))
);

