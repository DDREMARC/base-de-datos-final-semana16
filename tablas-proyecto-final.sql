-- =========================================================
-- TABLA 1: MENU_PLATOS — El Tío Sam Chifa (Oracle SQL)
-- =========================================================

CREATE TABLE menu_platos (
  id            NUMBER GENERATED BY DEFAULT AS IDENTITY,   -- autoincremental (Oracle 12c+)
  codigo        VARCHAR2(20 CHAR)  NOT NULL,               -- ej. CHI-001
  nombre        VARCHAR2(100 CHAR) NOT NULL,
  descripcion   VARCHAR2(500 CHAR),
  categoria     VARCHAR2(50 CHAR)  NOT NULL,
  precio        NUMBER(8,2)        NOT NULL,               -- en soles (S/)
  ingredientes  VARCHAR2(500 CHAR),
  imagen_url    VARCHAR2(255 CHAR),
  disponible    CHAR(1)            DEFAULT 'S' NOT NULL,   -- S = sí, N = no

  CONSTRAINT pk_menu_platos       PRIMARY KEY (id),
  CONSTRAINT uq_menu_platos_cod   UNIQUE (codigo),
  CONSTRAINT ck_platos_categoria  CHECK (categoria IN
                    ('Platos Comunes','Platos Mixtos','Sopas','Guarniciones','Dulces')),
  CONSTRAINT ck_platos_disponible CHECK (disponible IN ('S','N')),
  CONSTRAINT ck_platos_precio     CHECK (precio > 0)
);

-- Índice para buscar por categoría (la carta se filtra por pestañas)
CREATE INDEX idx_platos_categoria ON menu_platos (categoria);

COMMENT ON TABLE  menu_platos                IS 'Carta del Chifa: platos con precio en soles';
COMMENT ON COLUMN menu_platos.precio         IS 'Precio unitario en soles (S/), sin IGV separado';
COMMENT ON COLUMN menu_platos.disponible     IS 'S = disponible en carta, N = agotado/oculto';


